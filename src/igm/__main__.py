"""Run: PYTHONPATH=src python -m igm --command plan --days 7"""
import argparse
import json
import os
from pathlib import Path
from .commands import handle
from .instagram import InstagramError
from .queue import DraftQueueError


def load_from_event():
    event_file = os.getenv('GITHUB_EVENT_PATH')
    if not event_file:
        raise ValueError('GITHUB_EVENT_PATH not provided')
    event = json.loads(Path(event_file).read_text(encoding='utf-8'))
    issue = event.get('issue')
    if not issue:
        raise ValueError('This is not an Issues event')
    # Defense-in-depth; GitHub workflow also verifies the author.
    owner = os.getenv('GITHUB_REPOSITORY_OWNER', '')
    if issue.get('user', {}).get('login', '').lower() != owner.lower():
        raise ValueError('Only the repository owner may issue commands')
    if not issue.get('title', '').startswith('[IGM]'):
        raise ValueError('Issue title must start with [IGM]')
    body = (issue.get('body') or '').strip()
    if body.startswith('```json') and body.endswith('```'):
        body = body[len('```json'):-len('```')].strip()
    if len(body) > 10000:
        raise ValueError('Command exceeds 10,000 characters')
    # Принимаем первый JSON-объект; подписи вроде «Generated by …» после него игнорируются
    data, _ = json.JSONDecoder().raw_decode(body)
    return data


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument('--from-event', action='store_true')
    parser.add_argument('--command', default='help')
    parser.add_argument('--days', type=int, default=7)
    parser.add_argument('--start', default=None)
    parser.add_argument('--post-id', default=None)
    parser.add_argument('--payload', help='JSON object; for controlled local CLI use only')
    parser.add_argument('--out', default=None)
    args = parser.parse_args(argv)
    try:
        if args.from_event:
            data = load_from_event()
        elif args.payload:
            data = json.loads(args.payload)
        else:
            data = {'command': args.command, 'days': args.days, 'start': args.start, 'post_id': args.post_id}
        response = handle(data)
    except (ValueError, KeyError, TypeError, OSError, InstagramError, DraftQueueError) as ex:
        response = f'## Команда не выполнена\n\n{str(ex)}'
    except Exception as ex:
        # Hide tracebacks and potentially sensitive credentials from issue comments.
        response = f'## Команда не выполнена\n\nТип ошибки: {type(ex).__name__}. Проверь настройки и Actions logs.'
    if args.out:
        Path(args.out).write_text(response + '\n', encoding='utf-8')
    print(response)


if __name__ == '__main__':
    main()
